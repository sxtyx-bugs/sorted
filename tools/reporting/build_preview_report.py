import os
import sys
import datetime
import math

def entropy(data):
    if not data:
        return 0.0
    occ = {}
    for b in data:
        occ[b] = occ.get(b, 0) + 1
    ent = 0.0
    for count in occ.values():
        p = count / len(data)
        ent -= p * math.log2(p)
    return ent

def fmt_size(sz):
    if sz < 1024:
        return f"{sz} B"
    elif sz < 1024 * 1024:
        return f"{sz / 1024:.1f} KB"
    else:
        return f"{sz / (1024 * 1024):.2f} MB"

